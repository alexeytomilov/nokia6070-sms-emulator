function parse([top, s]) {
  const rows = s.split('/');
  return { top, rows, w: rows[0].length };
}

function rot180(g) {
  return { top: g.top, w: g.w, rows: g.rows.map(r => [...r].reverse().join('')).reverse() };
}

// Small glyph -> bold glyph, the way S40 bold relates to regular:
// x-height 7 -> 9 and caps 9 -> 11 (rows 4 and 7 repeat), interior columns
// repeat so width 4 -> 6, then every pixel is doubled to the right (2px stems).
// Lower-case arches get the S40 notch where a bar leaves a stem (real n, b, u, p, m).
// Checked against the real bold e, o, n, u, b, p: identical.
const BOLD_ROWS = [0, 1, 2, 3, 4, 4, 5, 6, 7, 7, 8, 9, 10, 11];
// Bold glyphs drawn by hand where the generator gives a poor shape (2 px stems, like н and п).
const BOLD_DRAWN = {
  'и': [3, '##...##/##...##/##..###/##..###/##.####/####.##/###..##/###..##/##...##'],
  'л': [3, '.######/.##..##/.##..##/.##..##/.##..##/.##..##/.##..##/.##..##/##...##'],
  'щ': [3, '##..##..##./##..##..##./##..##..##./##..##..##./##..##..##./##..##..##./##..##..##./##..##..##./###########/.........##'],
};
const NO_NOTCH = new Set([...'гтпшщцдляж']);   // square-cornered letters
function embolden(g, ch = '') {
  const full = Array.from({ length: 12 }, (_, r) => {
    const i = r - g.top;
    return i >= 0 && i < g.rows.length ? g.rows[i] : '.'.repeat(g.w);
  });
  const add = g.w >= 3 ? Math.min(g.w - 2, 3) : 0;
  const dup = new Set();
  for (let k = 0; k < add; k++) dup.add(1 + Math.floor((k + 0.5) * (g.w - 2) / add));
  const start = []; // small column -> first widened column
  for (let x = 0, p = 0; x < g.w; x++) { start[x] = p; p += dup.has(x) ? 2 : 1; }
  const widen = r => [...r].map((c, x) => dup.has(x) ? c + c : c).join('');
  const rows = BOLD_ROWS.map(r => widen(full[r]))
    .map(r => [...r + '.'].map((c, x) => (c === '#' || r[x - 1] === '#') ? '#' : '.').join('').split(''));

  const notch = ch && ch === ch.toLowerCase() && ch !== ch.toUpperCase() && !NO_NOTCH.has(ch);
  if (notch) {
    const on = (x, y) => full[y] && full[y][x] === '#';
    for (const y of [3, 9]) for (let x = 0; x < g.w; x++) {   // x-height top / baseline bars only
      if (!on(x, y)) continue;
      const up = on(x, y - 1), down = on(x, y + 1);
      if (up === down) continue;                 // not the end of a stem
      const L = on(x - 1, y), R = on(x + 1, y);
      if (L === R) continue;                     // no bar, or a T-junction
      const col = R ? start[x] + 1 : start[x];
      BOLD_ROWS.forEach((sr, by) => { if (sr === y) rows[by][col] = '.'; });
    }
  }
  return trim(rows.map(r => r.join('')));
}

function trim(rows) {
  let top = 0, bot = rows.length;
  while (top < bot && !rows[top].includes('#')) top++;
  while (bot > top && !rows[bot - 1].includes('#')) bot--;
  return { top, rows: rows.slice(top, bot), w: rows[0].length };
}

function build(src) {
  const out = {};
  for (const [c, d] of Object.entries(src)) out[c] = parse(d);
  return out;
}

const FONTS = (() => {
  const small = build({ ...SMALL_DRAWN, ...SMALL_REAL });
  for (const [c, l] of Object.entries(SAME_AS)) if (!small[c]) small[c] = small[l];

  const bold = {};
  for (const [c, g] of Object.entries(small)) bold[c] = embolden(g, c);
  const boldReal = build(BOLD_REAL);
  Object.assign(bold, boldReal, build(BOLD_DRAWN));
  for (const [c, l] of Object.entries(SAME_AS)) if (boldReal[l]) bold[c] = boldReal[l];

  const clock = build(CLOCK_REAL);
  clock['9'] = rot180(clock['6']);

  return {
    small: { glyphs: small, space: 3, gap: 1, height: 12 },
    bold:  { glyphs: bold,  space: 4, gap: 1, height: 14 },
    clock: { glyphs: clock, space: 4, gap: 1, height: 9 },
  };
})();

function glyphOf(font, ch) {
  return font.glyphs[ch] || font.glyphs[ch.toUpperCase()] || null;
}

function textWidth(fontName, s) {
  const f = FONTS[fontName];
  let w = 0;
  for (const ch of s) {
    const g = ch === ' ' ? null : glyphOf(f, ch);
    w += (g ? g.w : f.space) + f.gap;
  }
  return Math.max(0, w - f.gap);
}

// Draws pixel-exact text. (x, y) is the top-left of the font grid (row 0).
function drawText(ctx, fontName, s, x, y, color, align = 'left') {
  const f = FONTS[fontName];
  if (align === 'center') x = Math.round(x - textWidth(fontName, s) / 2);
  else if (align === 'right') x = x - textWidth(fontName, s) + 1;
  ctx.fillStyle = color;
  for (const ch of s) {
    const g = ch === ' ' ? null : glyphOf(f, ch);
    if (!g) { x += f.space + f.gap; continue; }
    g.rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++)
        if (row[rx] === '#') ctx.fillRect(x + rx, y + g.top + ry, 1, 1);
    });
    x += g.w + f.gap;
  }
}

function wrapText(fontName, s, maxW) {
  const out = [];
  for (const para of s.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(fontName, t) <= maxW) { line = t; continue; }
      if (line) out.push(line);
      let w = word;
      while (textWidth(fontName, w) > maxW) {
        let i = w.length;
        while (i > 1 && textWidth(fontName, w.slice(0, i)) > maxW) i--;
        out.push(w.slice(0, i)); w = w.slice(i);
      }
      line = w;
    }
    out.push(line);
  }
  return out;
}
