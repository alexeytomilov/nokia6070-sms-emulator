# Packs assets/*.png into assets.js as data: URLs, so index.html works when opened
# straight from disk (file://): images from files would taint the canvas there.
import base64, json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
data = {f'assets/{p.name}': 'data:image/png;base64,' + base64.b64encode(p.read_bytes()).decode()
        for p in sorted((root / 'assets').glob('*.png'))}
(root / 'assets.js').write_text('// Generated by tools/bundle_assets.py, do not edit.\nconst ASSET = ' + json.dumps(data, indent=0) + ';\n', encoding='utf-8')
print(len(data), 'images')
